"""题目家族 B —— 条件判断 / 循环重复 / 图形打印

面向 10~14 岁、正在准备 GESP Python 一级 / 二级的孩子。
所有期望输出都由 exlib.exercise() 真正运行参考答案得到，绝不手写。

命名约定：
    p_if_xxx    —— if 主题的一个「题型」（结构相同的题只算一个题型）
    p_loop_xxx  —— loop 主题的一个题型
    p_shape_xxx —— shape 主题的一个题型
每个题型函数内部用一个 for 循环换场景 / 换数据，产出 2~4 道题，
标题里带上具体数据，保证不会出现大批同名题。
"""

from exlib import exercise, self_check, pick, nums

SECTIONS = []


def section(fn):
    """把一个题型函数登记进 build()（按定义顺序执行）。"""
    SECTIONS.append(fn)
    return fn


def add(items, topic, level, title, desc, hint, answer, cases, tags=None):
    items.append(exercise(topic=topic, level=level, title=title, desc=desc,
                          hint=hint, answer=answer, cases=cases, tags=tags))


def build():
    items = []
    for fn in SECTIONS:
        fn(items)
    return items


